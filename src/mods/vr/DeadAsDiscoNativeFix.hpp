// Discovery only: neither a constructor nor a destructor is executed here.
// The caller must additionally prove the vtable's existing UE5.7 destructor
// contract and require a unique candidate before publishing these functions.
inline std::optional<uintptr_t> family_copy_vtable(const sdk::discovery::Memory& memory,
    uintptr_t entry, size_t unwind_size, uintptr_t module_base, size_t module_size) {
    if (unwind_size != family_copy_size || !in_module(entry, family_copy_size, module_base, module_size) ||
        !memory.executable || !memory.executable(memory.context, entry, family_copy_size) ||
        !code_matches(memory, entry, copy_entry) ||
        !code_matches(memory, entry + 0x1e, views) ||
        !code_matches(memory, entry + 0x2f, copy_source) ||
        !code_matches(memory, entry + 0x55, element_size) ||
        !code_matches(memory, entry + 0xa6, element_size) ||
        !code_matches(memory, entry + 0x73, array_copy) ||
        !code_matches(memory, entry + 0xc4, array_copy) ||
        !code_matches(memory, entry + 0x82, all_views) ||
        !code_matches(memory, entry + 0xd3, targets) ||
        !code_matches(memory, entry + 0x13d, additional) ||
        !code_matches(memory, entry + 0x3de, owned) ||
        !code_matches(memory, entry + 0x468, copy_tail)) { return {}; }

    std::array<uint8_t, 7> lea{};
    int32_t displacement{};
    if (!memory.load(entry + 0x28, lea) || lea[0] != 0x48 || lea[1] != 0x8d || lea[2] != 0x05) { return {}; }
    std::memcpy(&displacement, lea.data() + 3, sizeof(displacement));
    const auto table = sdk::discovery::relative_address(entry + 0x2f, displacement);
    if (!table || !in_module(*table, sizeof(uintptr_t), module_base, module_size)) { return {}; }

    // All out-of-line members must stay executable and inside the owning image, and both pointer arrays must use
    // the same allocation and copy helpers.
    std::array<std::optional<uintptr_t>, member_calls.size()> targets_of{};
    for (size_t i = 0; i < member_calls.size(); ++i) {
        targets_of[i] = direct_call(memory, entry + member_calls[i], module_base, module_size);
        if (!targets_of[i]) { return {}; }
    }
    if (targets_of[0] != targets_of[2] || targets_of[1] != targets_of[3]) { return {}; }
    return table;
}

